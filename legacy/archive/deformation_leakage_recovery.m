function recovery = deformation_leakage_recovery( ...
    D_filter_mm, A_final_turb_mm, acq_times, cfg, i_master, D_anchor_mm)
if nargin < 4 || isempty(cfg)
    cfg = struct();
end
if nargin < 5 || isempty(i_master)
    i_master = 1;
end
if nargin < 6
    D_anchor_mm = [];
end

validate_same_size(D_filter_mm, A_final_turb_mm);

if ~get_param(cfg, 'enable', true)
    zero_seq = zeros(size(D_filter_mm));
    zero_w = zeros(size(D_filter_mm, 1), 1);
    recovery = struct( ...
        'D_filter_mm', D_filter_mm, ...
        'A_final_turb_mm', A_final_turb_mm, ...
        'D_candidate_imm_mm', zero_seq, ...
        'W_def', zero_w, ...
        'W_sign', zero_w, ...
        'W_dyn', zero_w, ...
        'W_total', zero_w, ...
        'D_leak_mm', zero_seq, ...
        'D_recovered_mm', D_filter_mm, ...
        'config', cfg, ...
        'diagnostics', struct('enabled', false));
    return;
end

imm_result = extract_leakage_imm_kalman(A_final_turb_mm, acq_times, cfg, i_master);
[weights, weight_diagnostics] = build_leakage_weights( ...
    D_filter_mm, imm_result.D_candidate_mm, cfg, ...
    imm_result, D_anchor_mm);

D_candidate = imm_result.D_candidate_mm;
beta = ones(size(weights.W_def));
if get_param(cfg, 'use_dynamic_beta', false)
    beta_min = max(get_param(cfg, 'beta_min', 1.0), 0);
    beta_max = max(get_param(cfg, 'beta_max', beta_min), beta_min);
    beta = beta_min + (beta_max - beta_min) .* weights.W_def;
    D_candidate = bsxfun(@times, D_candidate, beta);
elseif get_param(cfg, 'use_fixed_beta', false)
    beta = get_param(cfg, 'fixed_beta', 1.0);
    D_candidate = beta .* D_candidate;
end
D_candidate = apply_candidate_limits(D_candidate, D_filter_mm, cfg);
D_candidate_for_leak = D_candidate;
D_candidate_for_leak(~isfinite(D_candidate_for_leak)) = 0;
D_leak = bsxfun(@times, weights.W_total, D_candidate_for_leak);
D_recovered = D_filter_mm + D_leak;

diagnostics = struct( ...
    'enabled', true, ...
    'imm', imm_result.diagnostics, ...
    'weights', weight_diagnostics, ...
    'beta_mean', mean(beta, 'omitnan'), ...
    'beta_p90', prctile(beta(isfinite(beta)), 90), ...
    'mean_abs_candidate_mm', mean(abs(D_candidate(:)), 'omitnan'), ...
    'mean_abs_leak_mm', mean(abs(D_leak(:)), 'omitnan'), ...
    'max_abs_leak_mm', max(abs(D_leak(:)), [], 'omitnan'), ...
    'active_weight_fraction', mean(weights.W_total > 0.05, 'omitnan'));

recovery = struct( ...
    'D_filter_mm', D_filter_mm, ...
    'A_final_turb_mm', A_final_turb_mm, ...
    'D_candidate_imm_mm', D_candidate, ...
    'W_def', weights.W_def, ...
    'W_sign', weights.W_sign, ...
    'W_dyn', weights.W_dyn, ...
    'W_total', weights.W_total, ...
    'D_leak_mm', D_leak, ...
    'D_recovered_mm', D_recovered, ...
    'config', cfg, ...
    'diagnostics', diagnostics);
end

function D_candidate = apply_candidate_limits(D_candidate, D_filter_mm, cfg)
max_abs_mm = get_param(cfg, 'max_abs_candidate_mm', inf);
if isfinite(max_abs_mm) && max_abs_mm > 0
    D_candidate = min(max(D_candidate, -max_abs_mm), max_abs_mm);
end

max_fraction = get_param(cfg, 'max_candidate_fraction_of_filter_endpoint', inf);
if isfinite(max_fraction) && max_fraction > 0
    filter_endpoint = abs(D_filter_mm(:, end) - D_filter_mm(:, 1));
    limit = max_fraction .* max(filter_endpoint, 1e-6);
    candidate_endpoint = D_candidate(:, end) - D_candidate(:, 1);
    scale = min(1, limit ./ max(abs(candidate_endpoint), 1e-6));
    scale(~isfinite(scale)) = 1;
    D_candidate = bsxfun(@times, D_candidate, scale);
end
end

function validate_same_size(a, b)
if ~isequal(size(a), size(b))
    error('D_filter_mm and A_final_turb_mm must have the same size.');
end
end

function value = get_param(s, name, default_value)
if isstruct(s) && isfield(s, name) && ~isempty(s.(name))
    value = s.(name);
else
    value = default_value;
end
end
