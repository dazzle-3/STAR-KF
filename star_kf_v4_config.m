function out = merge_struct(base, override)
out = base;
names = fieldnames(override);
for i = 1:numel(names)
    if ~isempty(override.(names{i}))
        out.(names{i}) = override.(names{i});
    end
end
end

function [optimization, variant_name] = apply_random_model_variant( ...
    optimization, variant)
if isstruct(variant)
    if isfield(variant, 'name')
        variant_name = char(variant.name);
    else
        variant_name = 'custom_random_model';
    end
    if isfield(variant, 'optimization')
        optimization = merge_struct( ...
            optimization, variant.optimization);
    else
        optimization = merge_struct(optimization, variant);
    end
    return;
end

variant_name = lower(strtrim(char(variant)));
variant_name = strrep(variant_name, '-', '_');
variant_name = strrep(variant_name, ' ', '_');
flags = {'weighted_recovery', 'network_dyy', ...
    'standardized_residuals', 'hetero_kriging_nugget'};
for i = 1:numel(flags)
    optimization.(flags{i}) = false;
end
switch variant_name
    case {'baseline', 'base', 'none'}
        variant_name = 'baseline';
    case {'weighted_recovery', 'weighted', 'wls'}
        optimization.weighted_recovery = true;
        variant_name = 'weighted_recovery';
    case {'network_dyy', 'dyy', 'pyy'}
        optimization.network_dyy = true;
        variant_name = 'network_dyy';
    case {'standardized_residuals', 'std_residuals', 'stdres'}
        optimization.standardized_residuals = true;
        variant_name = 'standardized_residuals';
    case {'hetero_kriging_nugget', 'hetero', 'hetero_kriging'}
        optimization.hetero_kriging_nugget = true;
        variant_name = 'hetero_kriging_nugget';
    case {'weighted_plus_hetero', 'weighted_hetero'}
        optimization.weighted_recovery = true;
        optimization.hetero_kriging_nugget = true;
        variant_name = 'weighted_plus_hetero';
    case {'dyy_plus_hetero', 'dyy_hetero'}
        optimization.network_dyy = true;
        optimization.hetero_kriging_nugget = true;
        variant_name = 'dyy_plus_hetero';
    case {'all_random_model', 'all', 'full_random_model'}
        optimization.weighted_recovery = true;
        optimization.network_dyy = true;
        optimization.standardized_residuals = true;
        optimization.hetero_kriging_nugget = true;
        variant_name = 'all_random_model';
    otherwise
        error('Unknown STAR-KF random-model variant: %s', char(variant));
end
