function result = filter_summary(sequence,variance,alpha,runtime)
% Marginals here are propagated observation noise, not posterior state error.
[np,n,nm]=size(alpha); final=reshape(alpha(:,end,:),np,nm);
[~,ix]=max(final,[],2); names=["cv","ca","seasonal"];
entropy=-sum(alpha.*log(max(alpha,realmin)),3)/log(nm);
result=struct('phi_seq_mm',sequence,'phi_seq_var_mm2',variance, ...
    'model_probs',final,'model_prob_series',alpha,'model_entropy',mean(entropy,2), ...
    'dominant_model',names(ix)', ...
    'model_stats',struct('cv',nnz(ix==1),'ca',nnz(ix==2),'seasonal',nnz(ix==3), ...
        'names',names,'counts',[nnz(ix==1),nnz(ix==2),nnz(ix==3)]), ...
    'runtime_stats',runtime,'q_final',[],'residual_mm',[]);
end
