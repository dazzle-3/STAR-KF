function final = finalize_joint_solution(data, tau_final_rad, R_final_mm2, cfg, a_final_rad)
%FINALIZE_JOINT_SOLUTION Re-run KF1+KF2 at fixed final atmosphere and R.

[Y_final_mm, observation_diagnostics] = ...
    build_corrected_observation_sequence( ...
    data, tau_final_rad, R_final_mm2, cfg);
deformation = two_stage_deformation_estimation( ...
    Y_final_mm, data, R_final_mm2, cfg, observation_diagnostics.operators);

deformation_joint_final_mm = deformation.D_joint_q;
timeseries_atm_corrected_mm = Y_final_mm;
phi_def_joint_ifg_rad = sequence_to_ifg( ...
    deformation_joint_final_mm, data.ifg_pairs, ...
    1 / data.scale_rad2mm);
residual_final_rad = data.phi_mat - phi_def_joint_ifg_rad - ...
    tau_final_rad;

i_master = min(max(round(cfg.i_master), 1), data.n_slc);
if nargin>=5
    turbulence_sequence_rad=a_final_rad;
else
    turbulence_sequence_rad = recover_sequence_with_random_model( ...
        tau_final_rad, data, i_master, R_final_mm2, ...
        observation_diagnostics.network_components, cfg.optimization);
end
turbulence_sequence_mm = rebase_to_reference_epoch( ...
    turbulence_sequence_rad .* data.scale_rad2mm, i_master);

data_contract = data;
data_contract.i_master = i_master;
audit = assert_star_kf_units_and_dimensions( ...
    data_contract, 'finalize_joint_solution', ...
    'deformation_joint_final_mm', deformation_joint_final_mm, ...
        'epoch_mm', ...
    'timeseries_atm_corrected_mm', timeseries_atm_corrected_mm, ...
        'epoch_mm', ...
    'tau_final_rad', tau_final_rad, 'ifg_rad', ...
    'residual_final_rad', residual_final_rad, 'ifg_rad');

final = struct( ...
    'deformation_joint_final_mm', deformation_joint_final_mm, ...
    'timeseries_atm_corrected_mm', timeseries_atm_corrected_mm, ...
    'turbulence_final_rad', tau_final_rad, ...
    'turbulence_sequence_mm', turbulence_sequence_mm, ...
    'residual_final_rad', residual_final_rad, ...
    'phi_def_joint_ifg_rad', phi_def_joint_ifg_rad, ...
    'R_final_mm2', R_final_mm2, ...
    'deformation', deformation, ...
    'observation_diagnostics', observation_diagnostics, ...
    'unit_audit', audit, ...
    'spatial_update_performed', false);
end

