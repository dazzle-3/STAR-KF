function [out, geometry_cache] = stomac_hybrid_turbulence_candidate( ...
    coord_km, resid_ifg_rad, ifg_pairs, n_slc, i_master, ...
    hybrid_cfg, source_mask, geometry_cache)
%STOMAC_HYBRID_TURBULENCE_CANDIDATE STOMAC EVD+BLUP inside STAR-KF.
%
% The input is the current STAR-KF atmosphere residual in IFG phase. This
% function uses the standalone STOMAC implementation for:
%   1) referenced network inversion to epoch residuals;
%   2) exponential IFG covariance fitting;
%   3) distance-wise nonnegative epoch-covariance inversion and refit;
%   4) rank-k epoch EVD projection;
%   5) full BLUP restoration and arithmetic window mosaicking.
% The returned candidate is differenced back to the original IFG network,
% so it is network-consistent before the unchanged STAR-KF controlled
% update. No STOMAC low-frequency cubic deformation model is used.

if nargin < 7 || isempty(source_mask)
    source_mask = true(size(resid_ifg_rad, 1), 1);
else
    source_mask = logical(source_mask(:));
end
if nargin < 8
    geometry_cache = [];
end

t_start = tic;
[n_pts, n_ifg] = size(resid_ifg_rad);
assert(size(coord_km, 1) == n_pts && size(coord_km, 2) == 2, ...
    'Hybrid STOMAC coordinates must be n_points-by-2.');
assert(size(ifg_pairs, 1) == n_ifg && size(ifg_pairs, 2) == 2, ...
    'Hybrid STOMAC IFG pairs do not match the residual stack.');
assert(max(ifg_pairs(:)) == n_slc, ...
    'Hybrid STOMAC network does not span all SLC epochs.');
assert(numel(source_mask) == n_pts, ...
    'Hybrid STOMAC source mask length is invalid.');

project_root = ensure_stomac_dependencies();
stomac_cfg = stomac_config(project_root);
stomac_cfg.evd_k = get_param(hybrid_cfg, 'evd_k', stomac_cfg.evd_k);

preserve_rng = get_param(hybrid_cfg, 'preserve_rng_state', true);
if preserve_rng
    rng_state = rng;
    rng_cleanup = onCleanup(@() rng(rng_state)); %#ok<NASGU>
end

[geometry_cache, geometry_reused] = prepare_geometry_cache( ...
    coord_km, source_mask, stomac_cfg, hybrid_cfg, geometry_cache);
data = geometry_cache.data_template;
data.ifg_stack = points_to_grid(resid_ifg_rad, geometry_cache);
data.pair_index = double(ifg_pairs);
data.reference_epoch = i_master;
data.time_years = (0:n_slc-1)' / max(n_slc - 1, 1);
data.phase_sign_convention = 'slave_minus_master';

[epoch_residual, sbas_info] = stomac_sbas_inversion(data);
[C0_ifg, d0_ifg, ifg_fit_status] = ...
    stomac_fit_ifg_covariance(data, stomac_cfg);
[sar_covariance, C0_sar, d0_sar, covariance_model] = ...
    stomac_invert_sar_covariance(C0_ifg, d0_ifg, ifg_pairs, ...
    geometry_cache.model_xy_m, stomac_cfg);

windows = geometry_cache.windows;
n_window = numel(windows);
n_model = numel(windows(1).model_linear_local);
modeled_residual = nan(n_model, n_slc, n_window);
for w = 1:n_window
    cube = epoch_residual(windows(w).row_index, ...
        windows(w).col_index, :);
    flat = reshape(cube, geometry_cache.window_rows * ...
        geometry_cache.window_cols, n_slc);
    modeled_residual(:, :, w) = ...
        flat(windows(w).model_linear_local, :);
end

[modeled_turbulence, eigenvalues, effective_rank, evd_info] = ...
    stomac_evd_turbulence(modeled_residual, sar_covariance, stomac_cfg);
[window_turbulence, blup_regularization] = stomac_blup_restore( ...
    modeled_turbulence, data, windows, C0_sar, d0_sar, stomac_cfg);
[epoch_turbulence, mosaic_coverage] = stomac_mosaic_windows( ...
    window_turbulence, windows, [data.row, data.col], data.mask);
candidate_grid = stomac_sequence_to_ifg(epoch_turbulence, ifg_pairs);
candidate_ifg = grid_to_points(candidate_grid, geometry_cache);

if any(~isfinite(candidate_ifg(source_mask, :)), 'all')
    error('Hybrid STOMAC produced a nonfinite candidate on valid points.');
end
candidate_epoch = grid_to_points(epoch_turbulence, geometry_cache);
roundtrip = candidate_epoch(:, ifg_pairs(:, 2)) - ...
    candidate_epoch(:, ifg_pairs(:, 1));
network_closure_rms_rad = rms_all(candidate_ifg - roundtrip);

fit_labels = string({ifg_fit_status.status});
sar_fit_labels = string({covariance_model.fit_status.status});
valid_coverage_mask = repmat(data.mask, 1, 1, n_slc);
quality = struct( ...
    'method', 'stomac_epoch_evd_blup', ...
    'geometry_reused', geometry_reused, ...
    'n_windows', n_window, ...
    'window_rows', geometry_cache.window_rows, ...
    'window_cols', geometry_cache.window_cols, ...
    'modeled_pixels_per_window', n_model, ...
    'actual_window_size_m', geometry_cache.spatial_info.actual_window_size_m, ...
    'actual_step_m', geometry_cache.spatial_info.actual_step_m, ...
    'actual_sampling_interval_m', ...
        geometry_cache.spatial_info.actual_sampling_interval_m, ...
    'evd_k', stomac_cfg.evd_k, ...
    'effective_rank_median', median(effective_rank, 'omitnan'), ...
    'ifg_fit_nonstandard_count', nnz(fit_labels ~= "fitted"), ...
    'sar_fit_nonstandard_count', nnz(sar_fit_labels ~= "fitted"), ...
    'C0_ifg_median', median(C0_ifg, 'omitnan'), ...
    'd0_ifg_median_km', median(d0_ifg, 'omitnan') / 1000, ...
    'C0_sar_median', median(C0_sar, 'omitnan'), ...
    'd0_sar_median_km', median(d0_sar, 'omitnan') / 1000, ...
    'blup_regularization_trigger_count', ...
        nnz([blup_regularization.triggered]), ...
    'mosaic_min_coverage', ...
        min(mosaic_coverage(valid_coverage_mask), [], 'all'), ...
    'network_design_rank', sbas_info.design_rank, ...
    'network_closure_rms_rad', network_closure_rms_rad, ...
    'candidate_rms_rad', rms_all(candidate_ifg), ...
    'epoch_candidate_rms_rad', rms_all(candidate_epoch), ...
    'eigenvalue_max', max(eigenvalues, [], 'all'), ...
    'evd_k_used_median', median(evd_info.k_used, 'omitnan'), ...
    'elapsed_sec', toc(t_start));

out = struct('phi_turb', candidate_ifg, 'quality', quality);
log_progress('HYBRID', ...
    ['STOMAC epoch EVD+BLUP candidate finished in %.2f s ', ...
     '(windows=%d, model=%d, d0_sar_med=%.3f km, closure=%.3g rad)'], ...
    quality.elapsed_sec, n_window, n_model, ...
    quality.d0_sar_median_km, quality.network_closure_rms_rad);
end

function [cache, reused] = prepare_geometry_cache( ...
        coord_km, source_mask, stomac_cfg, hybrid_cfg, cache)
coord_hash = simple_coord_hash(coord_km);
mask_hash = sum(find(source_mask) .* (1:nnz(source_mask))');
cache_valid = isstruct(cache) && isfield(cache, 'coord_hash') && ...
    cache.coord_hash == coord_hash && isfield(cache, 'mask_hash') && ...
    cache.mask_hash == mask_hash;
if cache_valid
    reused = true;
    return;
end

x_values = unique(coord_km(:, 1), 'sorted');
y_values = unique(coord_km(:, 2), 'sorted');
n_col = numel(x_values);
n_row = numel(y_values);
require_grid = get_param(hybrid_cfg, ...
    'require_complete_regular_grid', true);
if require_grid && n_row * n_col ~= size(coord_km, 1)
    error(['Hybrid STOMAC requires a complete regular grid: got %d ', ...
        'points but %d x %d coordinate levels.'], ...
        size(coord_km, 1), n_row, n_col);
end
[found_x, col_index] = ismember(coord_km(:, 1), x_values);
[found_y, row_index] = ismember(coord_km(:, 2), y_values);
assert(all(found_x & found_y), 'Could not map hybrid STOMAC grid coordinates.');
linear_index = sub2ind([n_row, n_col], row_index, col_index);
assert(numel(unique(linear_index)) == size(coord_km, 1), ...
    'Hybrid STOMAC grid coordinates contain duplicates.');

dx = diff(x_values);
dy = diff(y_values);
if isempty(dx), dx = 1; end
if isempty(dy), dy = dx; end
pixel_size_km = median([dx(:); dy(:)], 'omitnan');
spacing_tolerance = 1e-6 * max(1, abs(pixel_size_km));
assert(all(abs(dx - pixel_size_km) <= spacing_tolerance) && ...
    all(abs(dy - pixel_size_km) <= spacing_tolerance), ...
    'Hybrid STOMAC requires an equally spaced square-pixel grid.');

x_grid = nan(n_row, n_col);
y_grid = nan(n_row, n_col);
x_grid(linear_index) = coord_km(:, 1) * 1000;
y_grid(linear_index) = coord_km(:, 2) * 1000;
mask_grid = false(n_row, n_col);
mask_grid(linear_index) = source_mask;
data_template = struct( ...
    'row', n_row, ...
    'col', n_col, ...
    'pixel_size_m', pixel_size_km * 1000, ...
    'x_coordinates_m', x_grid, ...
    'y_coordinates_m', y_grid, ...
    'mask', mask_grid);
[windows, spatial_info] = ...
    stomac_build_spatial_windows(data_template, stomac_cfg);
first = windows(1);
x_first = x_grid(first.row_index, first.col_index);
y_first = y_grid(first.row_index, first.col_index);
model_linear = first.model_linear_local;
model_xy_m = [x_first(model_linear), y_first(model_linear)];

cache = struct( ...
    'coord_hash', coord_hash, ...
    'mask_hash', mask_hash, ...
    'linear_index', linear_index, ...
    'n_row', n_row, ...
    'n_col', n_col, ...
    'data_template', data_template, ...
    'windows', windows, ...
    'spatial_info', spatial_info, ...
    'window_rows', spatial_info.window_rows, ...
    'window_cols', spatial_info.window_cols, ...
    'model_xy_m', model_xy_m);
reused = false;
end

function grid = points_to_grid(values, cache)
n_slices = size(values, 2);
flat = nan(cache.n_row * cache.n_col, n_slices);
flat(cache.linear_index, :) = values;
grid = reshape(flat, cache.n_row, cache.n_col, n_slices);
end

function values = grid_to_points(grid, cache)
n_slices = size(grid, 3);
flat = reshape(grid, cache.n_row * cache.n_col, n_slices);
values = flat(cache.linear_index, :);
end

function project_root = ensure_stomac_dependencies()
module_dir = fileparts(mfilename('fullpath'));
star_dir = fileparts(module_dir);
project_root = fileparts(star_dir);
stomac_dir = fullfile(project_root, 'STOMAC_reproduction');
core_dir = fullfile(stomac_dir, 'core');
utils_dir = fullfile(stomac_dir, 'utils');
assert(isfile(fullfile(stomac_dir, 'stomac_config.m')), ...
    'STOMAC reproduction was not found at %s.', stomac_dir);
addpath(stomac_dir, core_dir, utils_dir);
end

function value = simple_coord_hash(coord)
weights = (1:size(coord, 1))';
value = sum((coord(:, 1) * 17 + coord(:, 2) * 31) .* weights);
end

function value = rms_all(values)
value = sqrt(mean(values(:).^2, 'omitnan'));
end

function value = get_param(params, name, default_value)
if isfield(params, name) && ~isempty(params.(name))
    value = params.(name);
else
    value = default_value;
end
end
