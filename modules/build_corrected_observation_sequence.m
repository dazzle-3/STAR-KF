function [Y_q_mm, diagnostics] = build_corrected_observation_sequence( ...
    data, tau_prev_rad, R_current_mm2, cfg)
%BUILD_CORRECTED_OBSERVATION_SEQUENCE Build G(phi_original-tau_prev; R).

i_master = min(max(round(cfg.i_master), 1), data.n_slc);
if ~isequal(size(tau_prev_rad), size(data.phi_mat))
    error('tau_prev_rad must match data.phi_mat.');
end
R_current_mm2 = double(R_current_mm2(:)');
if numel(R_current_mm2) ~= data.n_slc || ...
        any(~isfinite(R_current_mm2)) || any(R_current_mm2 < 0)
    error('R_current_mm2 must be a finite nonnegative epoch vector.');
end

corrected_ifg_rad = data.phi_mat - tau_prev_rad;
scale_sq = data.scale_rad2mm ^ 2;
slc_var_rad2 = R_current_mm2 ./ scale_sq;
ifg_white_rad2 = slc_var_rad2(data.ifg_pairs(:, 1)) + ...
    slc_var_rad2(data.ifg_pairs(:, 2));
QI=cfg.network.QI_rad2;
if isscalar(QI), QI=repmat(QI,1,data.n_ifg); end
network_components = struct( ...
    'ifg_white_rad2', ifg_white_rad2(:)', ...
    'ifg_extra_rad2', QI, ...
    'ifg_total_rad2', max(ifg_white_rad2(:)', 1e-12));

[Y_q_rad, operators] = recover_sequence_with_random_model( ...
    corrected_ifg_rad, data, i_master, R_current_mm2, ...
    network_components, cfg.optimization);
Y_q_mm = rebase_to_reference_epoch( ...
    Y_q_rad .* data.scale_rad2mm, i_master);

data_contract = data;
data_contract.i_master = i_master;
audit = assert_star_kf_units_and_dimensions( ...
    data_contract, 'build_corrected_observation_sequence', ...
    'Y_q_mm', Y_q_mm, 'epoch_mm', ...
    'corrected_ifg_rad', corrected_ifg_rad, 'ifg_rad', ...
    'R_current_mm2', R_current_mm2, 'epoch_var_row');
operator_audits=cell(size(operators.SigmaY,3),1);
for j=1:numel(operator_audits)
    operator_audits{j}=assert_star_kf_units_and_dimensions(data_contract, ...
        'network_operator_covariance','G',operators.G(:,:,j),'network_operator_mm_per_rad', ...
        'SigmaY',operators.SigmaY(:,:,j),'epoch_cov_mm2');
end

raw_difference = Y_q_mm - data.z_d_raw;
diagnostics = struct( ...
    'semantics', 'G(phi_original_minus_tau_prev;R_current,random_model)', ...
    'corrected_ifg_rad', corrected_ifg_rad, ...
    'operators', operators, ...
    'operator_audits',{operator_audits}, ...
    'network_components', network_components, ...
    'finite_fraction', mean(isfinite(Y_q_mm(:))), ...
    'raw_support_rms_mm', sqrt(mean(raw_difference(:).^2, 'omitnan')), ...
    'unit_audit', audit);
end

