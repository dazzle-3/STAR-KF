function out = joint_inversion(data, cfg, checkpoint_dir)
%JOINT_INVERSION Unique STAR-KF two-stage joint inversion orchestrator.

total_tic = tic;
if nargin < 3, checkpoint_dir=''; end
validate_formal_configuration(cfg);
data.i_master = min(max(round(cfg.i_master), 1), data.n_slc);
i_master = data.i_master;
n_max = cfg.joint.n_outer_iters;
continue_after_convergence = false;
if isfield(cfg,'diagnostics') && isfield(cfg.diagnostics,'continue_after_convergence')
    continue_after_convergence = cfg.diagnostics.continue_after_convergence;
end
if ~islogical(continue_after_convergence) || ~isscalar(continue_after_convergence)
    error('STAR_KF:DiagnosticControl','continue_after_convergence must be a logical scalar.');
end
first_criterion_iteration = 0;
stopping_policy='joint_state';
if isfield(cfg.convergence,'policy'), stopping_policy=cfg.convergence.policy; end
if ~strcmp(stopping_policy,'joint_state')
    error('STAR_KF:StoppingPolicy','The accepted release uses joint_state stopping.');
end

[B,~,~,~]=network_incidence(data.ifg_pairs,data.n_slc,i_master);
a_prev_rad=cfg.initial.atmosphere_epoch_rad;
if isscalar(a_prev_rad), a_prev_rad=repmat(a_prev_rad,data.n_pts,data.n_slc); end
if ~isequal(size(a_prev_rad),[data.n_pts,data.n_slc]) || any(~isfinite(a_prev_rad(:))) || any(a_prev_rad(:,i_master)~=0)
    error('STAR_KF:InitialAtmosphere','Given a0 must be finite and zero at reference.');
end
tau_prev_rad=a_prev_rad*B';
R_current_mm2=cfg.initial.R_epoch_mm2;
if isscalar(R_current_mm2), R_current_mm2=repmat(R_current_mm2,1,data.n_slc); end
R_current_mm2=R_current_mm2(:)';
if numel(R_current_mm2)~=data.n_slc || any(~isfinite(R_current_mm2)|R_current_mm2<0)
    error('STAR_KF:InitialVariance','Invalid given R0.');
end
fixed_spatial_support=isfinite(data.phi_mat)&all(isfinite(data.coord_km),2);
fixed_convergence_support=[];
previous = [];
convergence_streak = 0;
shared_covariance_cache = [];
kriging_geometry_cache = [];
stomac_hybrid_geometry_cache = [];
iterations = cell(n_max, 1);
diagnostic_objective_history = nan(n_max, 1);
D_anchor_mm = [];
first_round = 1;
resumed_iteration_sec=0;
if ~isempty(checkpoint_dir)
    if ~isfolder(checkpoint_dir), mkdir(checkpoint_dir); end
    for p=1:n_max
        path=fullfile(checkpoint_dir,sprintf('round_%02d.mat',p));
        if ~isfile(path), break; end
        s=load(path,'record','rng_after','checkpoint_cfg');
        assert(isequaln(s.checkpoint_cfg,cfg) && s.record.iteration==p, ...
            'Checkpoint configuration or round mismatch.');
        iterations{p}=s.record;
        diagnostic_objective_history(p)=s.record.diagnostic_objective;
        resumed_iteration_sec=resumed_iteration_sec+s.record.timing.iteration_sec;
        if s.record.convergence.terminate && first_criterion_iteration==0
            first_criterion_iteration=p;
        end
        first_round=p+1;
    end
    if first_round>1
        z=iterations{first_round-1};
        D_anchor_mm=iterations{1}.D1_q;
        fixed_convergence_support=struct('D',isfinite(iterations{1}.D_joint_q), ...
            'tau',fixed_spatial_support,'R',isfinite(iterations{1}.R_next));
        previous=struct('support',fixed_convergence_support,'D_joint_mm',z.D_joint_q, ...
            'tau_rad',z.tau_q,'E_final_rad',z.E_final_q,'R_next_mm2',z.R_next);
        tau_prev_rad=z.tau_q; a_prev_rad=z.a_q; R_current_mm2=z.R_next;
        convergence_streak=z.convergence.streak;
        rng(s.rng_after);
        log_progress('CHECKPOINT','Restored %d complete outer rounds',first_round-1);
        if z.convergence.terminate && ~continue_after_convergence
            first_round=n_max+1;
        end
        clear s z;
    end
end

log_progress('JOINT', ...
    ['Starting unique two-stage joint flow: iterations=%d, ', ...
     'fresh covariance, VCE and spatial updates every round'], n_max);

for q = first_round:n_max
    iteration_tic = tic;
    timing = struct();
    log_progress('ITER', 'Iteration %d/%d: building G(phi-tau_prev)', ...
        q, n_max);

    step_tic = tic;
    [Y_q, observation_diagnostics] = ...
        build_corrected_observation_sequence( ...
        data, tau_prev_rad, R_current_mm2, cfg);
    timing.observation_sequence_sec = toc(step_tic);

    step_tic = tic;
    deformation = two_stage_deformation_estimation( ...
        Y_q, data, R_current_mm2, cfg, observation_diagnostics.operators);
    timing.two_stage_kalman_sec = toc(step_tic);
    if q == 1
        D_anchor_mm = deformation.D1_q;
    end

    phi_def_joint_ifg_rad = sequence_to_ifg( ...
        deformation.D_joint_q, data.ifg_pairs, ...
        1 / data.scale_rad2mm);
    R_atm_q = data.phi_mat - phi_def_joint_ifg_rad;
    assert_star_kf_units_and_dimensions( ...
        data, 'pre_spatial_residual', ...
        'D_joint_q', deformation.D_joint_q, 'epoch_mm', ...
        'P_joint_q', deformation.P_joint_q, 'epoch_mm2', ...
        'R_atm_q', R_atm_q, 'ifg_rad');

    % Fresh covariance and VCE are mandatory in every formal iteration.
    step_tic = tic;
    atmosphere_source_mask = true(data.n_pts, 1);
    known_noise=diag(observation_diagnostics.operators.QI)';
    [covariance, shared_covariance_cache] = stomac_covariance( ...
        data.coord_km, R_atm_q, cfg.kernel, ...
        shared_covariance_cache, atmosphere_source_mask, known_noise);
    timing.covariance_sec = toc(step_tic);

    step_tic = tic;
    vce = vce_estimation( ...
        covariance, data.ifg_pairs, data.n_slc, cfg.vce, i_master);
    timing.vce_sec = toc(step_tic);

    step_tic = tic;
    [kriging, kriging_geometry_cache] = kriging_interpolation( ...
        data.coord_km,R_atm_q,covariance,vce,data.ifg_pairs, ...
        cfg.kriging,cfg.kernel,[],atmosphere_source_mask,kriging_geometry_cache);
    kriging.quality.candidate_source='kriging';
    if any(~kriging.support_mask(fixed_spatial_support))
        error('STAR_KF:SpatialSupportLoss','Required fixed spatial support is unavailable.');
    end
    tau_candidate_q = kriging.phi_turb;
    timing.kriging_sec = toc(step_tic);

    step_tic = tic;
    vsp=zeros(1,data.n_ifg);
    for k=1:data.n_ifg
        vsp(k)=mean(kriging.phi_turb_var(fixed_spatial_support(:,k),k));
    end
    [~,spmapper]=ifg_variance_to_epoch_variance(vsp,data.ifg_pairs,data.n_slc,i_master,cfg.variance_mapping);
    [tau_q,tau_update,a_q] = controlled_turbulence_update( ...
        a_prev_rad,tau_candidate_q,kriging.phi_turb_var, ...
        cfg.turbulence_update,data,spmapper.mapper_phase,fixed_spatial_support);
    timing.turbulence_update_sec = toc(step_tic);

    E_final_q = data.phi_mat - phi_def_joint_ifg_rad - tau_q;
    assert_star_kf_units_and_dimensions( ...
        data, 'complete_joint_update', ...
        'tau_q', tau_q, 'ifg_rad', ...
        'E_final_q', E_final_q, 'ifg_rad');

    step_tic = tic;
    [R_next, R_components] = propagate_joint_uncertainty( ...
        kriging.phi_turb_var, vce, E_final_q, ...
        deformation.P_joint_q, R_current_mm2, data, cfg, fixed_spatial_support);
    timing.uncertainty_sec = toc(step_tic);

    fresh_spatial_update = true;
    convergence = compute_full_joint_convergence( ...
        deformation.D_joint_q, tau_q, E_final_q, R_next, ...
        previous, data, cfg.convergence, q, convergence_streak, ...
        fresh_spatial_update);
    stopping_D=deformation.D_joint_q;
    timing.conditional_stopping_pass_sec=0; % retained output field; no extra pass
    convergence_streak = convergence.streak;
    if convergence.terminate && first_criterion_iteration==0
        first_criterion_iteration = q;
    end

    diagnostic_objective = complete_iteration_diagnostic_objective( ...
        E_final_q, R_next, data.scale_rad2mm, cfg.joint);
    diagnostic_objective_history(q) = diagnostic_objective;
    timing.iteration_sec = toc(iteration_tic);

    weights = deformation.weights;
    iterations{q} = struct( ...
        'iteration', q, ...
        'Y_q', Y_q, ...
        'D1_q', deformation.D1_q, ...
        'P1_q', deformation.P1_q, ...
        'E1_q', deformation.E1_q, ...
        'D2_raw_q', deformation.D2_raw_q, ...
        'P2_q', deformation.P2_q, ...
        'WD',weights.WD,'WU',weights.WU,'WA',weights.WA,'aM',weights.aM, ...
        'W2', weights.W2, ...
        'D2_q', deformation.D2_q, ...
        'D_joint_q', deformation.D_joint_q, ...
        'P_joint_q', deformation.P_joint_q, ...
        'R_atm_q', R_atm_q, ...
        'covariance', covariance, ...
        'VCE', vce, ...
        'vce', vce, ...
        'tau_candidate_q', tau_candidate_q, ...
        'tau_candidate_var_q', kriging.phi_turb_var, ...
        'tau_q', tau_q, 'a_q',a_q, ...
        'beta_q', tau_update.beta_q, ...
        'E_final_q', E_final_q, ...
        'R_current', R_current_mm2, ...
        'R_next', R_next, ...
        'R_next_components', R_components, ...
        'Delta_D', convergence.Delta_D, ...
        'Delta_tau', convergence.Delta_tau, ...
        'Delta_E', convergence.Delta_E, ...
        'Delta_R', convergence.Delta_R, ...
        'diagnostic_objective', diagnostic_objective, ...
        'convergence', convergence, ...
        'observation_diagnostics', observation_diagnostics, ...
        'deformation_diagnostics', deformation.diagnostics, ...
        'operator_pixel_indices',deformation.operator_pixel_indices,'operators',{deformation.operators}, ...
        'kf1_diagnostics', compact_filter_diagnostics(deformation.kf1), ...
        'kf2_diagnostics', compact_filter_diagnostics(deformation.kf2), ...
        'tau_update_diagnostics', tau_update, ...
        'kriging', kriging, ...
        'fresh_spatial_update', fresh_spatial_update, ...
        'timing', timing);

    candidate_energy = deformation.diagnostics.candidate_energy_mm2;
    accepted_energy = deformation.diagnostics.accepted_energy_mm2;
    accepted_fraction = deformation.diagnostics.acceptance.accepted_pixel_fraction;
    residual_energy_mm2 = mean(E_final_q(:) .^ 2, 'omitnan') .* ...
        data.scale_rad2mm ^ 2;
    R_quantiles = prctile(R_next(isfinite(R_next)), [10, 50, 90]);
    log_progress('ITER', ...
        ['Iteration %d/%d complete: KF2 candidate/accepted=%.4f/', ...
         '%.4f mm^2, accepted_pixels=%.3f, tau_change=%.4f rad, ', ...
         'E_final=%.4f mm^2, R[p10/med/p90]=%.3f/%.3f/%.3f, ', ...
         'Delta[D/tau/E/R]=%s/%s/%s/%s, elapsed=%.2f s'], ...
        q, n_max, candidate_energy, accepted_energy, accepted_fraction, ...
        tau_update.candidate_change_rms_rad, residual_energy_mm2, ...
        R_quantiles(1), R_quantiles(2), R_quantiles(3), ...
        format_scalar(convergence.Delta_D), ...
        format_scalar(convergence.Delta_tau), ...
        format_scalar(convergence.Delta_E), ...
        format_scalar(convergence.Delta_R), timing.iteration_sec);

    if isempty(fixed_convergence_support)
        fixed_convergence_support=struct('D',isfinite(stopping_D), ...
            'tau',fixed_spatial_support,'R',isfinite(R_next));
    end
    previous = struct( ...
        'support',fixed_convergence_support, ...
        'D_joint_mm', stopping_D, ...
        'tau_rad', tau_q, ...
        'E_final_rad', E_final_q, ...
        'R_next_mm2', R_next);
    tau_prev_rad = tau_q; a_prev_rad=a_q;
    R_current_mm2 = R_next;

    if ~isempty(checkpoint_dir)
        write_round_checkpoint(checkpoint_dir,iterations{q},cfg);
    end

    if convergence.terminate
        log_progress('JOINT', ...
            ['Stopping criterion at iteration %d: metric below %.4f ', ...
             'for %d consecutive eligible full updates'], ...
            q, convergence.thresholds.C, convergence.streak);
        if continue_after_convergence
            log_progress('JOINT','Diagnostic continuation: criterion recorded; proceeding to round %d limit.',n_max);
        else
            break;
        end
    end
end

n_completed = find(~cellfun('isempty',iterations),1,'last');
iterations = iterations(1:n_completed);
diagnostic_objective_history = ...
    diagnostic_objective_history(1:n_completed);
last_iteration = iterations{end};

log_progress('FINAL', ...
    ['Fixing tau_final/R_final and running one final KF1+KF2 pass; ', ...
     'no Kriging or leakage back-substitution follows']);
final_tic = tic;
final = finalize_joint_solution( ...
    data, tau_prev_rad, R_current_mm2, cfg, a_prev_rad);
finalization_sec = toc(final_tic);
final.d_final=frobenius_relative_change(final.deformation_joint_final_mm,last_iteration.D_joint_q,fixed_convergence_support.D);

phi_def_filter_ifg_rad = sequence_to_ifg( ...
    final.deformation.D1_q, data.ifg_pairs, 1 / data.scale_rad2mm);
uncertainty = build_final_uncertainty( ...
    final.deformation, R_current_mm2, ...
    last_iteration.R_next_components);
convergence_history = build_convergence_history(iterations, cfg);
runtime_profile = build_runtime_profile( ...
    iterations, toc(total_tic)+resumed_iteration_sec, finalization_sec);

out = struct( ...
    'iterations', {iterations}, ...
    'atmosphere_epoch_final_rad',a_prev_rad, ...
    'criterion_fulfilled',last_iteration.convergence.terminate, ...
    'criterion_ever_fulfilled',first_criterion_iteration>0, ...
    'criterion_first_satisfied_iteration',first_criterion_iteration, ...
    'diagnostic_continue_after_convergence',continue_after_convergence, ...
    'stopping_policy',stopping_policy, ...
    'iteration_limit_reached',n_completed==n_max, ...
    'termination_reason',termination_reason(last_iteration.convergence.terminate,continue_after_convergence,stopping_policy), ...
    'deformation_joint_final', final.deformation_joint_final_mm, ...
    'timeseries_atm_corrected', final.timeseries_atm_corrected_mm, ...
    'turbulence_final', final.turbulence_final_rad, ...
    'residual_final', final.residual_final_rad, ...
    'deformation_joint_final_mm', final.deformation_joint_final_mm, ...
    'timeseries_atm_corrected_mm', final.timeseries_atm_corrected_mm, ...
    'turbulence_final_rad', final.turbulence_final_rad, ...
    'residual_final_rad', final.residual_final_rad, ...
    'R_final_mm2', R_current_mm2, ...
    'P_joint_final_mm2', final.deformation.P_joint_q, ...
    'phi_turb_seq_mm', final.turbulence_sequence_mm, ...
    'phi_seq_filter_mm', final.deformation.D1_q, ...
    'phi_seq_corrected_mm', final.deformation_joint_final_mm, ...
    'phi_turb_final_rad', final.turbulence_final_rad, ...
    'phi_def_filter_ifg_rad', phi_def_filter_ifg_rad, ...
    'phi_def_corrected_ifg_rad', final.phi_def_joint_ifg_rad, ...
    'filter_result', final.deformation.kf1, ...
    'kf2_result', final.deformation.kf2, ...
    'finalization', final, ...
    'covariance', last_iteration.covariance, ...
    'vce', last_iteration.vce, ...
    'kriging', last_iteration.kriging, ...
    'updated_r', R_current_mm2, ...
    'uncertainty', uncertainty, ...
    'D_anchor_mm', D_anchor_mm, ...
    'anchor_semantics', 'first_iteration_KF1_diagnostic_only', ...
    'diagnostic_objective_history', diagnostic_objective_history, ...
    'convergence_history', convergence_history, ...
    'runtime_profile', runtime_profile, ...
    'output_contract', struct( ...
        'canonical_fields', {cfg.output.canonical_fields}, ...
        'deformation_joint_final_unit', 'LOS mm', ...
        'timeseries_atm_corrected_unit', 'LOS mm', ...
        'turbulence_final_unit', 'rad IFG absolute field', ...
        'residual_final_unit', 'rad IFG', ...
        'deformation_covariance_semantics', ...
            cfg.output.deformation_covariance_semantics, ...
        'post_kriging_deformation_recovery', false, ...
        'final_spatial_update', false, ...
        'formal_flow', 'KF1_KF2_then_spatial_modeling'));

if cfg.optimization.standardized_residuals
    out.standardized_residuals = standardized_residual_products( ...
        final.residual_final_rad, last_iteration.R_next_components);
end
log_progress('JOINT', 'Joint inversion finished in %.2f s', ...
    runtime_profile.total_sec);
end

function write_round_checkpoint(folder,record,checkpoint_cfg)
rng_after=rng;
path=fullfile(folder,sprintf('round_%02d.mat',record.iteration));
temp=fullfile(folder,sprintf('round_%02d.partial.mat',record.iteration));
assert(~isfile(path),'Refusing to overwrite a complete checkpoint.');
save(temp,'record','rng_after','checkpoint_cfg','-v7.3','-nocompression');
[ok,msg]=movefile(temp,path); assert(ok,msg);
log_progress('CHECKPOINT','Saved complete outer round %d',record.iteration);
end

function validate_formal_configuration(cfg)
if ~strcmp(cfg.spatial_estimator.variant,'kriging') || ...
        ~ismember(cfg.kernel.model_variant,{'dual_matern_anisotropic_stationary', ...
        'single_matern_anisotropic_stationary'})
    error('STAR_KF:FormalSpatial','Formal target uses matched direct dual-Matern mean and variance.');
end
required = {'kalman', 'kalman_kf2', 'kf2_acceptance', 'kernel', ...
    'vce', 'kriging', 'joint', 'turbulence_update', ...
    'uncertainty', 'convergence', 'optimization', 'output'};
for i = 1:numel(required)
    if ~isfield(cfg, required{i}) || ~isstruct(cfg.(required{i}))
        error('Missing formal configuration section cfg.%s.', required{i});
    end
end
if cfg.joint.n_outer_iters < 1
    error('cfg.joint.n_outer_iters must be positive.');
end
if ~isfield(cfg.convergence, 'joint_state_tol') || ...
        ~isscalar(cfg.convergence.joint_state_tol) || ...
        ~isfinite(cfg.convergence.joint_state_tol) || ...
        cfg.convergence.joint_state_tol <= 0
    error('cfg.convergence.joint_state_tol must be positive and finite.');
end
end

function value = complete_iteration_diagnostic_objective( ...
    E_final_rad, R_next_mm2, scale_rad2mm, cfg)
residual_mm = E_final_rad .* scale_rad2mm;
residual_energy = mean(residual_mm(:) .^ 2, 'omitnan');
value = residual_energy + cfg.diagnostic_objective_r_weight .* ...
    median(R_next_mm2, 'omitnan');
end

function diagnostics = compact_filter_diagnostics(filter_result)
diagnostics = struct( ...
    'model_stats', filter_result.model_stats, ...
    'runtime_stats', filter_result.runtime_stats, ...
    'mean_model_entropy', mean(filter_result.model_entropy, 'omitnan'), ...
    'median_posterior_variance_mm2', ...
        median(filter_result.phi_seq_var_mm2(:), 'omitnan'));
end

function uncertainty = build_final_uncertainty( ...
    deformation, R_final_mm2, components)
P_joint = deformation.P_joint_q;
pixel_std = sqrt(max(mean(P_joint, 2, 'omitnan'), 0));
epoch_std = sqrt(max(mean(P_joint, 1, 'omitnan'), 0));
uncertainty = struct( ...
    'pixel_std_mm', pixel_std, ...
    'epoch_std_mm', epoch_std, ...
    'pixel_ci95_mm', 1.96 .* pixel_std, ...
    'epoch_ci95_mm', 1.96 .* epoch_std, ...
    'model_uncertainty', deformation.kf1.model_entropy, ...
    'kf2_model_uncertainty', deformation.kf2.model_entropy, ...
    'observation_std_mm', sqrt(max(R_final_mm2, 0)), ...
    'components', components, ...
    'covariance_semantics', ...
        'fixed-fit observation-noise propagation with KF1/KF2 cross-covariance; excludes fitted-quantity variability and bias');
end

function history = build_convergence_history(iterations, cfg)
n = numel(iterations);
Delta_D = nan(n, 1);
Delta_tau = nan(n, 1);
Delta_E = nan(n, 1);
Delta_R = nan(n, 1);
C = nan(n, 1);
converged = false(n, 1);
fresh = false(n, 1);
for i = 1:n
    conv = iterations{i}.convergence;
    Delta_D(i) = conv.Delta_D;
    Delta_tau(i) = conv.Delta_tau;
    Delta_E(i) = conv.Delta_E;
    Delta_R(i) = conv.Delta_R;
    C(i) = conv.C_diagnostic;
    converged(i) = conv.terminate;
    fresh(i) = conv.fresh_spatial_update;
end
history = struct( ...
    'Delta_D', Delta_D, ...
    'Delta_tau', Delta_tau, ...
    'Delta_E', Delta_E, ...
    'Delta_R', Delta_R, ...
    'C_diagnostic', C, ...
    'converged', converged, ...
    'fresh_spatial_update', fresh, ...
    'config', cfg.convergence);
end

function profile = build_runtime_profile(iterations, total_sec, final_sec)
n = numel(iterations);
fields = {'observation_sequence_sec', 'two_stage_kalman_sec', ...
    'covariance_sec', 'vce_sec', 'kriging_sec', ...
    'turbulence_update_sec', 'uncertainty_sec', 'conditional_stopping_pass_sec', 'iteration_sec'};
profile = struct('total_sec', total_sec, ...
    'finalization_sec', final_sec, 'n_iterations', n, ...
    'fresh_spatial_updates', n);
for f = 1:numel(fields)
    values = nan(n, 1);
    for i = 1:n
        values(i) = iterations{i}.timing.(fields{f});
    end
    profile.(fields{f}) = values;
end
profile.avg_kriging_neighbors = ...
    iterations{end}.kriging.quality.mean_neighbors;
end

function out = standardized_residual_products(residual_rad, components)
ifg_var = components.ifg_vce_white_rad2 + ...
    components.ifg_kriging_latent_rad2 + ...
    components.ifg_residual_positive_rad2;
ifg_std = sqrt(max(ifg_var, 1e-12));
z = residual_rad ./ ifg_std;
out = struct( ...
    'z_ifg', z, ...
    'ifg_std_rad', ifg_std, ...
    'mean_abs_z_by_ifg', mean(abs(z), 1, 'omitnan'), ...
    'p95_abs_z_by_ifg', prctile(abs(z), 95, 1), ...
    'global_mean_abs_z', mean(abs(z(:)), 'omitnan'), ...
    'global_p95_abs_z', prctile(abs(z(:)), 95));
end

function text = format_scalar(value)
if isnan(value)
    text = 'NaN';
elseif isinf(value)
    text = 'Inf';
else
    text = sprintf('%.4f', value);
end
end

function value = get_struct_field(s, name, default_value)
if isstruct(s) && isfield(s, name) && ~isempty(s.(name))
    value = s.(name);
else
    value = default_value;
end
end

function reason=termination_reason(criterion,diagnostic_continuation,policy)
if diagnostic_continuation
    reason='diagnostic_iteration_limit';
elseif criterion
    if strcmp(policy,'joint_state'), reason='joint_state_criterion';
    else, reason=[policy,'_criterion']; end
else
    reason='iteration_limit';
