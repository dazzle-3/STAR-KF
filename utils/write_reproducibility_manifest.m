function write_reproducibility_manifest(root,input_dir,output_dir,cfg,result)
files=[dir(fullfile(root,'*.m'));dir(fullfile(root,'modules','*.m'));dir(fullfile(root,'utils','*.m'));dir(fullfile(root,'evaluation','*.m'))];
sources=struct('path',{},'sha256',{});
for k=1:numel(files)
    path=fullfile(files(k).folder,files(k).name);
    sources(k)=struct('path',path,'sha256',file_sha256(path));
end
inputs=struct('path',{},'sha256',{},'role',{});
names={cfg.input_file,cfg.kf_input_file,cfg.truth_file};
for k=1:3
    path=fullfile(input_dir,names{k});
    if ~isfile(path), continue; end
    role='solver_or_unit_diagnostic'; if k==3, role='post_estimation_evaluation_only'; end
    inputs(end+1)=struct('path',path,'sha256',file_sha256(path),'role',role); %#ok<AGROW>
end
manifest=struct('implementation_base',root,'matlab_version',version,'config',cfg, ...
    'source_fingerprints',sources,'input_fingerprints',inputs, ...
    'criterion_fulfilled',result.criterion_fulfilled,'iteration_limit_reached',result.iteration_limit_reached, ...
    'criterion_ever_fulfilled',result.criterion_ever_fulfilled, ...
    'criterion_first_satisfied_iteration',result.criterion_first_satisfied_iteration, ...
    'diagnostic_continue_after_convergence',result.diagnostic_continue_after_convergence, ...
    'termination_reason',result.termination_reason,'n_complete_updates',numel(result.iterations), ...
    'stopping_policy',result.stopping_policy, ...
    'd_final_diagnostic',result.finalization.d_final,'output_units',result.output_contract, ...
    'fitted_quantity_variability_and_model_bias_included',false, ...
    'working_variance_is_independent_physical_decomposition',false);
fid=fopen(fullfile(output_dir,'reproducibility_manifest.json'),'w','n','UTF-8');
if fid<0, error('STAR_KF:Manifest','Cannot write reproducibility manifest.'); end
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(manifest,'PrettyPrint',true));
end
